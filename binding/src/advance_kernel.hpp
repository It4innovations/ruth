#pragma once

// The advance kernel: a direct port of ruth/simulator/route.py
// (get_vehicle_speed / move_on_segment / generate_fcds / advance_vehicle for a
// single vehicle). It is a pure function of (task, frozen GlobalView): it reads
// no shared mutable state, so it is safe to run concurrently over many tasks.

#include <vector>

#include "advance_types.hpp"
#include "globalview.hpp"   // FCDRecord, GlobalView

namespace ruthlib {

/// Convert km/h to m/s (matches segment.py:speed_kph_to_mps).
double speed_kph_to_mps(double kph);

/// Advance one vehicle by one step against the frozen GlobalView `gv`.
///
/// @param t                   the vehicle's current state + local route window
/// @param gv                  frozen LoS snapshot (read-only)
/// @param departure_epoch_us  simulation departure time, epoch MICROSECONDS
/// @param los_tolerance_s     LoS time tolerance, seconds
/// @param out_fcds            FCD samples generated by the move are appended here
/// @return the resulting movement delta
AdvanceDelta advance_one_vehicle(const AdvanceTask& t,
                                 const GlobalView& gv,
                                 int64_t departure_epoch_us,
                                 double los_tolerance_s,
                                 std::vector<FCDRecord>& out_fcds);

}  // namespace ruthlib
